package mgddl

import (
	"strconv"
	"strings"

	"github.com/gsoultan/storm/compile/mongo"
	"github.com/gsoultan/storm/schema"
)

// Commands renders s as MongoDB commands, one JSON document each, in the order
// they must run: every collection, then every collection's indexes.
//
// They are plain command documents so anything that can run a command can
// apply them — runtime/mgdrv's Exec, mongosh's db.runCommand, a migration tool.
func Commands(s *schema.Schema) ([]string, error) {
	if err := Check(s); err != nil {
		return nil, err
	}
	enums := map[string]*schema.Enum{}
	for _, e := range s.Enums {
		enums[e.Name] = e
	}
	var out []string
	for _, t := range s.Tables {
		out = append(out, createCollection(t, enums))
	}
	for _, t := range s.Tables {
		if ix := createIndexes(t); ix != "" {
			out = append(out, ix)
		}
	}
	return out, nil
}

// Create renders Commands as a mongosh script.
func Create(s *schema.Schema) (string, error) {
	cmds, err := Commands(s)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Generated by storm for MongoDB. Apply with mongosh against the target database:\n")
	b.WriteString("//   mongosh \"$MONGODB_URI\" --file this-file.js\n")
	for _, c := range cmds {
		b.WriteString("db.runCommand(")
		b.WriteString(c)
		b.WriteString(");\n")
	}
	return b.String(), nil
}

// createCollection is the collection and its validator.
//
// The validator is what makes a NOT NULL column and a column type mean
// something here: without one, a collection accepts any document, and a
// generated scanner would meet a string where it expects a long. "strict" and
// "error" so an invalid write fails rather than being logged and kept.
//
// A NULL is a field that is absent or null, so a nullable field is not
// required and admits null; a NOT NULL field is required and does not.
func createCollection(t *schema.Table, enums map[string]*schema.Enum) string {
	var props, required []string
	for _, c := range t.Columns {
		f := mongo.Field(t, c.Name)
		bt, _ := mongo.BSONType(c)
		var p strings.Builder
		p.WriteString(mongo.Str(f))
		p.WriteString(`:{"bsonType":`)
		if c.NotNull {
			p.WriteString(mongo.Str(bt))
			required = append(required, mongo.Str(f))
		} else {
			p.WriteString(`[` + mongo.Str(bt) + `,"null"]`)
		}
		if c.Type.Name == schema.TypeVarchar && c.Type.Size > 0 {
			p.WriteString(`,"maxLength":` + strconv.Itoa(c.Type.Size))
		}
		if e, ok := enums[c.Type.Name]; ok && c.Type.Enum {
			p.WriteString(`,"enum":[`)
			for i, l := range e.Labels {
				if i > 0 {
					p.WriteByte(',')
				}
				p.WriteString(mongo.Str(l))
			}
			if !c.NotNull {
				p.WriteString(`,null`)
			}
			p.WriteByte(']')
		}
		p.WriteByte('}')
		props = append(props, p.String())
	}
	var b strings.Builder
	b.WriteString(`{"create":` + mongo.Str(t.Name) + `,"validator":{"$jsonSchema":{"bsonType":"object"`)
	if len(required) > 0 {
		b.WriteString(`,"required":[` + strings.Join(required, ",") + `]`)
	}
	b.WriteString(`,"properties":{` + strings.Join(props, ",") + `}}}`)
	b.WriteString(`,"validationLevel":"strict","validationAction":"error"}`)
	return b.String()
}

// createIndexes is every UNIQUE and every index, or "" for none.
//
// A nullable unique key is TRANSLATED, as on SQL Server, because the two
// engines disagree about NULL and the disagreement changes answers: SQL's
// UNIQUE lets any number of rows leave the key NULL, and MongoDB's indexes a
// missing field as null and lets ONE document do it. A partialFilterExpression
// requiring every nullable key field to hold a value indexes exactly the rows
// PostgreSQL's index constrains. NULLS NOT DISTINCT is then the plain form.
func createIndexes(t *schema.Table) string {
	var ixs []string
	for _, u := range t.Uniques {
		keys := make([]schema.IndexColumn, len(u.Columns))
		for i, c := range u.Columns {
			keys[i] = schema.IndexColumn{Name: c}
		}
		name := u.Name
		if name == "" {
			name = t.UniqueName(u)
		}
		ixs = append(ixs, index(t, name, keys, true, false, false))
	}
	for _, ix := range t.Indexes {
		name := ix.Name
		if name == "" {
			name = t.IndexName(ix)
		}
		ixs = append(ixs, index(t, name, ix.Columns, ix.Unique, ix.NullsNotDistinct, ix.Invisible))
	}
	if len(ixs) == 0 {
		return ""
	}
	return `{"createIndexes":` + mongo.Str(t.Name) + `,"indexes":[` + strings.Join(ixs, ",") + `]}`
}

func index(t *schema.Table, name string, keys []schema.IndexColumn, unique, nullsEqual, hidden bool) string {
	var key, partial []string
	for _, k := range keys {
		f := mongo.Field(t, k.Name)
		dir := "1"
		if k.Desc {
			dir = "-1"
		}
		key = append(key, mongo.Str(f)+":"+dir)
		if c := t.Column(k.Name); unique && !nullsEqual && c != nil && !c.NotNull {
			bt, _ := mongo.BSONType(c)
			partial = append(partial, mongo.Str(f)+`:{"$type":`+mongo.Str(bt)+`}`)
		}
	}
	s := `{"key":{` + strings.Join(key, ",") + `},"name":` + mongo.Str(name)
	if unique {
		s += `,"unique":true`
	}
	if len(partial) > 0 {
		s += `,"partialFilterExpression":{` + strings.Join(partial, ",") + `}`
	}
	if hidden {
		// MySQL's invisible index, and with the same purpose: maintained but
		// unused, so dropping it can be rehearsed.
		s += `,"hidden":true`
	}
	return s + `}`
}
