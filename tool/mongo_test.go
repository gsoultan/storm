package tool

// MongoDB is a back end rather than a dialect, and the CLI is where that has
// to stay invisible: the same -dialect flag, the same commands, and a refusal
// naming the construct for everything that does not port.

import (
	"strings"
	"testing"

	"github.com/gsoultan/storm"
	"github.com/gsoultan/storm/codegen"
	"github.com/gsoultan/storm/examples/library/model"
)

func TestMongoIsAKnownDialect(t *testing.T) {
	s, err := storm.Build(model.All()...)
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"mongo", "mongodb"} {
		tgt, err := parseDialect(name)
		if err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if tgt.dialect != codegen.DialectMongo {
			t.Errorf("%s resolved to %v", name, tgt.dialect)
		}
		out, err := tgt.ddl(s)
		if err != nil {
			t.Fatal(err)
		}
		for _, want := range []string{`"create":"authors"`, `"$jsonSchema"`, `"createIndexes":"books"`} {
			if !strings.Contains(out, want) {
				t.Errorf("ddl lacks %s:\n%s", want, out)
			}
		}
	}
	if err := portable("mongo", s); err != nil {
		t.Errorf("the library model ports: %v", err)
	}
}

func TestGenerateMongoUsesItsOwnGenerator(t *testing.T) {
	s, err := storm.Build(model.All()...)
	if err != nil {
		t.Fatal(err)
	}
	files, err := packageFor(s, codegen.PackageOptions{Import: modulePath, Dialect: codegen.DialectMongo})
	if err != nil {
		t.Fatal(err)
	}
	src := string(files["book/book.gen.go"])
	if !strings.Contains(src, "generated by storm for MongoDB") || strings.Contains(src, "SELECT") {
		t.Fatalf("not the MongoDB generator's output:\n%.400s", src)
	}
	// And the SQL generator refuses it rather than falling through to
	// PostgreSQL, which is what its zero value is.
	if _, err := codegen.Package(s, codegen.PackageOptions{Import: modulePath, Dialect: codegen.DialectMongo}); err == nil {
		t.Fatal("codegen.Package generated SQL for a MongoDB target")
	}
}

func TestMongoRefusesTheCatalogueCommands(t *testing.T) {
	for _, cmd := range []string{"diff", "verify", "explain", "import", "watch"} {
		err := Run([]string{cmd, "-dialect", "mongo"})
		if err == nil || !strings.Contains(err.Error(), "mongo") {
			t.Errorf("storm %s -dialect mongo: %v", cmd, err)
		}
	}
}
