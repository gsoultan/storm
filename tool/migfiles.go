// migFile is one file `storm diff` writes: an up migration, or the down that
// undoes it under the same version.
type migFile struct {
	name string
	body string
	note string // the parenthesis on the → line
}

const generatedHeader = "-- generated by storm; review before applying\n"

// migrationFiles splits a plan into the files a migration runner can apply,
// starting at version seq, and — when down is non-nil — the down migration
// for each one under the same version.
//
// The split is the one the runner forces. An enum label addition commits
// before anything uses the label (SQLSTATE 55P04); the transactional steps
// share one file; constraint validations follow in a file of their own, so the
// scan does not run under the lock of the ADD it validates; and every
// CREATE/DROP INDEX CONCURRENTLY is alone in a file, because it refuses to run
// inside a transaction block and a runner wraps each file in one.
//
// golang-migrate rolls back one version at a time, newest first, so each down
// undoes exactly its own version's up, and the newest up's down runs first.
func migrationFiles(plan migrate.Plan, down *migrate.Plan, name string, seq int) ([]migFile, error) {
	var enums, inTx, validate, alone []migrate.Change
	for _, ch := range plan.Changes {
		switch {
		case ch.AddsEnumValue():
			enums = append(enums, ch)
		case ch.NoTransaction:
			alone = append(alone, ch)
		case ch.Validates():
			validate = append(validate, ch)
		default:
			inTx = append(inTx, ch)
		}
	}

	// The down plan, split the same way: its concurrent index steps pair one
	// to one with the up's, by index name and the opposite direction, and
	// everything else undoes the transactional file.
	var downTx []migrate.Change
	downAlone := map[string]migrate.Change{}
	if down != nil {
		for _, ch := range down.Changes {
			if ch.NoTransaction {
				ix, build := ch.Index()
				downAlone[key(ix, build)] = ch
				continue
			}
			downTx = append(downTx, ch)
		}
	}

	var files []migFile
	ver := func(suffix string) string { return fmt.Sprintf("%04d_%s%s", seq, name, suffix) }
	addDown := func(base, body string, destructive bool) {
		if down == nil {
			return
		}
		header := generatedHeader + "-- undoes " + base + ".up.sql\n"
		note := "down"
		if destructive {
			header += "-- DESTRUCTIVE: the steps marked storm:destructive below lose data, such as\n" +
				"-- the rows written to a table since the up migration created it\n"
			note += ", DESTRUCTIVE"
		}
		files = append(files, migFile{name: base + ".down.sql", body: header + "\n" + body, note: note})
	}

	for i := range enums {
		base := ver(fmt.Sprintf("_enum_%d", i+1))
		files = append(files, migFile{
			name: base + ".up.sql",
			body: generatedHeader +
				"-- adds an enum label. It is alone in this file because PostgreSQL will not\n" +
				"-- let a later statement use the new label until this one has COMMITTED.\n\n" +
				enums[i].SQL + "\n",
			note: "1 step, enum label",
		})
		addDown(base, "-- nothing to run: PostgreSQL cannot remove an enum label (it has no DROP VALUE)\n", false)
		seq++
	}
	if len(inTx) > 0 {
		base := ver("")
		p := migrate.Plan{Changes: inTx}
		note := fmt.Sprintf("%d steps", len(inTx))
		if p.Destructive() {
			note += ", DESTRUCTIVE"
		}
		files = append(files, migFile{
			name: base + ".up.sql",
			body: generatedHeader + fmt.Sprintf("-- %d step(s)\n\n", len(inTx)) + p.SQL(),
			note: note,
		})
		d := migrate.Plan{Changes: downTx}
		addDown(base, d.SQL(), d.Destructive())
		downTx = nil
		seq++
	}
	if len(validate) > 0 {
		base := ver("_validate")
		files = append(files, migFile{
			name: base + ".up.sql",
			body: generatedHeader +
				"-- checks the existing rows against constraints added NOT VALID. Apart from the\n" +
				"-- ADD on purpose: the scan here blocks no reader and no writer, and inside the\n" +
				"-- ADD's transaction it would run under the ADD's lock.\n\n" +
				migrate.Plan{Changes: validate}.SQL(),
			note: fmt.Sprintf("%d step(s), validation", len(validate)),
		})
		// The constraints themselves go in the transactional file's down; a
		// validation changes no definition, so there is nothing here to undo.
		body := "-- nothing to run: validating a constraint changes no definition\n"
		addDown(base, body, false)
		seq++
	}
	for i, ch := range alone {
		base := ver(fmt.Sprintf("_concurrently_%d", i+1))
		files = append(files, migFile{
			name: base + ".up.sql",
			body: generatedHeader + migrate.NoTransactionMarker + "\n" +
				"-- this statement cannot run inside a transaction block: apply this file on its own, outside one\n\n" +
				ch.SQL + "\n",
			note: "1 step, outside a transaction",
		})
		if down != nil {
			ix, build := ch.Index()
			undo, ok := downAlone[key(ix, !build)]
			if !ok {
				return nil, fmt.Errorf("storm diff -down: no reverse for %q; write this down migration by hand", ch.SQL)
			}
			delete(downAlone, key(ix, !build))
			addDown(base, migrate.Plan{Changes: []migrate.Change{undo}}.SQL(), undo.Destructive)
		}
		seq++
	}
	// What is left over had no transactional file to undo. When it is only
	// the comments that stand for a step with no reverse — an enum label —
	// it goes in the first down, which is the last to run.
	for _, ch := range downTx {
		if !strings.HasPrefix(ch.SQL, "--") {
			downAlone[ch.SQL] = ch
		}
	}
	if len(downAlone) > 0 {
		// Every reverse step has to land in some version's down, or rolling
		// back leaves the schema neither here nor there.
		return nil, errors.New("storm diff -down: the reverse plan has steps no up migration accounts for; " +
			"write the down migrations by hand")
	}
	if len(downTx) > 0 {
		for i := range files {
			if strings.HasSuffix(files[i].name, ".down.sql") {
				files[i].body += migrate.Plan{Changes: downTx}.SQL()
				break
			}
		}
	}
	return files, nil
}

func key(index string, build bool) string {
	if build {
		return "build " + index
	}
	return "drop " + index
}

// checkSum refuses to build on a migrations directory that no longer matches
// its storm.sum. A directory without one is fine: it has never been summed.
func checkSum(out string) error {
	err := migratesum.Check(out)
	if errors.Is(err, migratesum.ErrNoSum) {
		return nil
	}
	return err
}

// writeMigrations writes the files and then storm.sum, or with dryRun prints
// what it would have written and writes nothing at all.
func writeMigrations(out string, files []migFile, dryRun bool) error {
	if dryRun {
		for _, f := range files {
			fmt.Printf("── %s (%s)\n%s\n", filepath.Join(out, f.name), f.note, strings.TrimRight(f.body, "\n"))
		}
		fmt.Println("dry run — nothing was written")
		return nil
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(out, f.name), []byte(f.body), 0o644); err != nil {
			return err
		}
		fmt.Printf("→ %s (%s)\n", filepath.Join(out, f.name), f.note)
	}
	if _, err := migratesum.Write(out); err != nil {
		return fmt.Errorf("write %s: %w", migratesum.File, err)
	}
	fmt.Printf("→ %s\n", filepath.Join(out, migratesum.File))
	fmt.Println("review and commit — storm diff applies nothing")
	return nil
}
