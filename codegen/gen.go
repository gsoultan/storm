// Package codegen emits Go from the schema IR.
//
// Output is byte-deterministic across runs and machines: `storm verify` fails
// CI on a plain diff, so any nondeterminism here would show up as spurious
// churn in every pull request.
package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"

	"github.com/gsoultan/storm/compile/pgsql"
	"github.com/gsoultan/storm/runtime"
	"github.com/gsoultan/storm/schema"
)

// Options control emission.
type Options struct {
	Package string // package name for the generated file
	Import  string // module path of the runtime, e.g. "github.com/gsoultan/storm"
	Table   string // which table to emit

	// Dialect selects the back end. The zero value is PostgreSQL, so every
	// existing caller keeps the target it already had and its generated output
	// is byte-identical.
	Dialect Dialect

	// BatchTopColumns are the columns this table is batch-loaded by — the
	// foreign keys of has-many relations pointing at it. Each one gets a
	// per-parent limited loader.
	BatchTopColumns []string

	// TopStrategy selects the greatest-n-per-group lowering. The zero value is
	// DefaultTopStrategy, which is chosen by measurement.
	TopStrategy TopStrategy

	// DefaultOrder is the ordering a query with no Order() gets; empty means
	// the primary key.
	//
	// Structured, not a raw SQL string: ordering is chosen per query now, so
	// the terms have to become tokens, and a string cannot be one. A column
	// that is not filterable is a generation error rather than SQL that fails
	// on first use.
	DefaultOrder []OrderTerm
}

// OrderTerm is one default ordering term.
type OrderTerm struct {
	Column string
	Desc   bool
}

// File renders one table's package.
func File(s *schema.Schema, o Options) ([]byte, error) {
	t := s.Table(o.Table)
	if t == nil {
		return nil, fmt.Errorf("codegen: no table %q", o.Table)
	}
	// The old cap here was fifteen columns, because four bits of operator per
	// column had to fit in a 64-bit shape. The tree IR replaced that mask with
	// a token stream months ago and the cap outlived it, silently generating
	// no predicates at all for a sixteenth column. The real limit is the width
	// of Tok's column field, and exceeding it is an error.
	cols := filterable(t)
	if len(cols) > runtime.MaxCols {
		return nil, fmt.Errorf(
			"codegen: table %s has %d filterable columns; the token column field holds %d — "+
				"split the table, or narrow it with a projection",
			t.Name, len(cols), runtime.MaxCols)
	}

	for _, c := range t.Columns {
		if err := checkNumeric(t.Name, c); err != nil {
			return nil, err
		}
	}

	// Refused before a line is emitted. compile/myddl already turns these away
	// in DDL; a read path that accepted them would let the two halves disagree
	// about what the target supports.
	for _, c := range t.Columns {
		if !o.Dialect.supports(c) {
			return nil, fmt.Errorf(
				"codegen: table %s column %s is %s, which %s cannot decode — "+
					"`storm portable %s` lists every such column and what to use instead",
				t.Name, c.Name, c.Type.SQL(), o.Dialect, o.Dialect)
		}
	}
	g := &gen{s: s, t: t, o: o, cols: cols, dec: decodersFor(o.Dialect, o.Import)}
	g.header()
	g.rowType()
	g.opConstants()
	g.treeQuery()
	g.predType()
	g.colHandles()
	g.treePreds()
	g.existsPreds()
	g.chained()
	g.compile()
	g.scanner()
	g.treeBind()
	g.terminals()
	g.batchTop()
	g.projections()
	g.aggregates()
	g.joins()
	g.arcs()
	g.recursive()
	g.writes()

	if g.err != nil {
		return nil, g.err
	}

	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("codegen: generated code does not parse: %w", err)
	}
	return src, nil
}

type gen struct {
	buf  bytes.Buffer
	s    *schema.Schema
	t    *schema.Table
	o    Options
	cols []colInfo
	// dec is the decoder family this file targets, resolved once from
	// o.Dialect so no emitter has to ask again.
	dec decoders

	// err is the first construct the target cannot express. Emitters set it
	// and return; File reports it instead of writing a file that is quietly
	// missing a predicate. Silence is not an option AGENTS.md allows.
	err error
}

// colInfo is a filterable column with everything the emitters need, resolved
// once so no pass re-derives it.
type colInfo struct {
	col    *schema.Column
	kind   kind
	goBase string
}

func (c colInfo) Name() string { return c.col.Name }

func (g *gen) p(format string, a ...any) {
	fmt.Fprintf(&g.buf, format, a...)
	g.buf.WriteByte('\n')
}

// filterable returns the columns a query may filter on, in table order so the
// output is stable.
func filterable(t *schema.Table) []colInfo {
	var out []colInfo
	for _, c := range t.Columns {
		k := goKind(c)
		if k == kindUnsupported {
			continue
		}
		out = append(out, colInfo{col: c, kind: k, goBase: baseGoType(c)})
	}
	return out
}

func (g *gen) header() {
	g.p("// Code generated by storm %s. DO NOT EDIT.", Version())
	g.p("// source: table %s", g.t.Name)
	g.p("")
	g.p("package %s", g.o.Package)
	g.p("")
	g.p("import (")
	g.p("\t%q", "context")
	g.p("\t%q", "errors")
	g.p("\t%q", "net/netip")
	g.p("\t%q", "time")
	g.p("")
	g.p("\t%q", g.o.Import+"/runtime")
	g.p(")")
	g.p("")
	g.p("var (")
	g.p("\t_ = time.Time{}")
	g.p("\t_ = netip.Prefix{}")
	g.p(")")
	g.p("")
}

func (g *gen) rowType() {
	g.p("// Row is what a full read returns: the model struct with relations")
	g.p("// replaced by their scalar foreign keys and *T rewritten to Null[T].")
	g.p("type Row struct {")
	for _, c := range g.t.Columns {
		if !readable(c) {
			continue
		}
		g.p("\t%s %s", exportName(c.Name), goType(c))
	}
	g.p("}")
	g.p("")
}

// Operators, in a fixed order so the op nibble is stable across runs.
// ops is the operator set as it appears in the *Go* API: the method suffix and
// whether it binds a value. The SQL each one lowers to belongs to the back end
// in compile/, not here — see pgsql.Frag.
//
// Argument-taking operators must come first: bind tests `op-1 < opsWithArg`
// with a single unsigned compare and that range check is only valid if the
// argument-less operators are last.
var ops = []struct {
	name string // method suffix
	args int
}{
	{"Eq", 1},
	{"NotEq", 1},
	{"Gt", 1},
	{"Gte", 1},
	{"Lt", 1},
	{"Lte", 1},
	{"Like", 1},
	{"Matches", 1},
	{"WebSearch", 1},
	{"Overlaps", 1},
	{"ContainsRange", 1},
	{"ContainedBy", 1},
	{"In", 1},
	{"IsNull", 0},
	{"IsNotNull", 0},
}

const opNone = 0 // nibble 0 means "no predicate on this column"

func (g *gen) opConstants() {
	g.p("// Operator ids. Argument-taking operators are numbered first, so the")
	g.p("// bind loop tests `op-1 < opsWithArg` with one unsigned compare.")
	g.p("const (")
	for i, op := range ops {
		g.p("\top%s runtime.Op = %d", op.name, i+1)
	}
	g.p("\t// Existence operators apply to PSEUDO-COLUMNS — relation slots past")
	g.p("\t// the real columns in the frag table. Argless, like IsNull: the")
	g.p("\t// fragment is constant, which is what lets a semi-join ride the")
	g.p("\t// ordinary predicate machinery and compose under And/Or/Not free.")
	g.p("\topExists    runtime.Op = %d", len(ops)+1)
	g.p("\topNotExists runtime.Op = %d", len(ops)+2)
	g.p(")")
	g.p("")
	g.p("const nCols = %d", len(g.cols))
	g.p("")
}

func (g *gen) chained() {
	g.p("// Chained predicate sugar. Identical to Where(Col.Op(v)).")
	for _, c := range g.cols {
		for _, op := range ops {
			if !opApplies(op.name, c.kind, c.col) {
				continue
			}
			m := exportName(c.Name()) + op.name
			h := exportName(c.Name())
			switch {
			case op.name == "In":
				if predArraySlot(c) == "" {
					continue
				}
				g.p("func (q Query) %s(v ...%s) Query { return q.Where(%s.In(v...)) }", m, c.goBase, h)
			case op.args == 0:
				g.p("func (q Query) %s() Query { return q.Where(%s.%s()) }", m, h, op.name)
			default:
				g.p("func (q Query) %s(v %s) Query { return q.Where(%s.%s(v)) }", m, c.goBase, h, op.name)
			}
		}
	}
	g.p("")
}

func (g *gen) compile() {
	g.p("const selectPrefix = `%s`", pgsql.SelectPrefix(g.t.Name, readableCols(g.t)))
	g.p("const countPrefix = `%s`", pgsql.CountPrefix(g.t.Name))
	g.p("const existsPrefix = `%s`", pgsql.ExistsPrefix(g.t.Name))
	g.p("const existsSuffix = `%s`", pgsql.ExistsSuffix())
	g.p("const limitSuffix = `%s`", pgsql.LimitOffsetSuffix(false))
	g.p("const limitOffsetSuffix = `%s`", pgsql.LimitOffsetSuffix(true))
	g.p("// orderTable is every ordering this table can express, lowered at build")
	g.p("// time. ORDER BY is chosen per query, so it cannot be a constant — but it")
	g.p("// still must not be built from strings at run time.")
	g.p("var orderTable = [nCols][%d]string{", pgsql.NDirections)
	for _, c := range g.cols {
		g.p("\t{ // %s", c.Name())
		for d := 0; d < pgsql.NDirections; d++ {
			g.p("\t\t%q,", pgsql.OrderTerm(d, pgsql.Ident(c.Name())))
		}
		g.p("\t},")
	}
	g.p("}")
	g.p("")
	g.p("// identTable is each column's bare quoted name, for the left side of a")
	g.p("// row comparison.")
	g.p("var identTable = [nCols]string{")
	for _, c := range g.cols {
		g.p("\t%q,", pgsql.Ident(c.Name()))
	}
	g.p("}")
	g.p("")
	g.p("var lowering = runtime.Lowering{")
	g.p("\tFrag:  fragOf,")
	g.p("\tOrder: orderOf,")
	g.p("\tOB:    runtime.Order{Lead: %q, Sep: %q},", pgsql.OrderLead, pgsql.OrderSep)
	g.p("\tIdent: func(col uint32) string {")
	g.p("\t\tif col >= nCols {")
	g.p("\t\t\treturn \"\"")
	g.p("\t\t}")
	g.p("\t\treturn identTable[col]")
	g.p("\t},")
	g.p("\tRowCmp: func(op uint32) string {")
	g.p("\t\tif op == runtime.CmpLt {")
	g.p("\t\t\treturn %q", pgsql.RowCmpOp(1))
	g.p("\t\t}")
	g.p("\t\treturn %q", pgsql.RowCmpOp(0))
	g.p("\t},")
	g.p("\tTupleOpen:  %q,", pgsql.TupleOpen)
	g.p("\tTupleSep:   %q,", pgsql.TupleSep)
	g.p("\tTupleClose: %q,", pgsql.TupleClose)
	g.p("}")
	g.p("")
	g.p("func orderOf(dir, col uint32) string {")
	g.p("\tif col >= nCols || int(dir) >= len(orderTable[0]) {")
	g.p("\t\treturn \"\"")
	g.p("\t}")
	g.p("\treturn orderTable[col][dir]")
	g.p("}")
	g.p("")
	g.p("// fragTable is every predicate this table can produce, lowered at build")
	g.p("// time. Runtime splices; it never formats.")
	nRels := len(existsRelations(g.t))
	g.p("var fragTable = [%d][%d]runtime.Frag{", len(g.cols)+nRels, len(ops)+3)
	for _, c := range g.cols {
		g.p("\t{ // %s", c.Name())
		g.p("\t\t{}, // opNone")
		for _, op := range ops {
			if !opApplies(op.name, c.kind, c.col) {
				g.p("\t\t{},")
				continue
			}
			a, b, ok := pgsql.Frag(op.name, pgsql.Ident(c.Name()))
			if !ok {
				g.err = fmt.Errorf("codegen: table %s column %s: target postgres has no lowering for operator %s",
					g.t.Name, c.Name(), op.name)
				return
			}
			g.p("\t\t{A: %q, B: %q},", a, b)
		}
		g.p("\t\t{},")
		g.p("\t\t{},")
		g.p("\t},")
	}
	g.existsFragRows()
	g.p("}")
	g.p("")
	g.p("func fragOf(op, col uint32) runtime.Frag {")
	g.p("\t// Bounded by the table, not nCols: existence pseudo-columns live past")
	g.p("\t// the real ones. Order, ident and arena lookups stay nCols-bounded,")
	g.p("\t// so a pseudo-column can never be ordered by, cursored on, or bound.")
	g.p("\tif int(col) >= len(fragTable) || int(op) >= len(fragTable[0]) {")
	g.p("\t\treturn runtime.Frag{}")
	g.p("\t}")
	g.p("\treturn fragTable[col][op]")
	g.p("}")
	g.p("")
	g.p("// defaultOrder is what a query with no Order() uses.")
	g.p("//")
	g.p("// It is never empty. A read without ORDER BY has no defined order, so")
	g.p("// paging one is a bug waiting for a plan change to expose it — and the")
	g.p("// primary key is the cheapest total order available.")
	g.p("var defaultOrder = [%d]runtime.Tok{", len(g.defaultOrder()))
	for _, t := range g.defaultOrder() {
		g.p("\truntime.MakeOrder(%s, %d), // %s", t.dirConst, t.col, t.comment)
	}
	g.p("}")
	g.p("")
	g.p("var (")
	g.p("\tcache      = runtime.NewTreeCache()")
	g.p("\toffsetCache = runtime.NewTreeCache()")
	g.p("\tcountCache = runtime.NewTreeCache()")
	g.p("\texistsCache = runtime.NewTreeCache()")
	g.p(")")
	g.p("")
	g.p("// Shapes reports how many distinct query structures have compiled.")
	g.p("// `storm lint` uses it to catch a builder minting a statement per request.")
	g.p("func Shapes() int { return cache.Shapes() }")
	g.p("")
	g.p("// ShapeFlushes reports how many times a shape cache in this package hit")
	g.p("// runtime.ShapeCap and dropped. Zero is the expected value forever:")
	g.p("// nonzero means a call site is minting structures from request data")
	g.p("// rather than from code, and the fix is that call site, not a bigger")
	g.p("// cap. Export it as a gauge — it is the cheapest early warning that a")
	g.p("// filter screen turned into 2^n statements.")
	g.p("func ShapeFlushes() int {")
	g.p("\treturn cache.Flushes() + offsetCache.Flushes() +")
	g.p("\t\tcountCache.Flushes() + existsCache.Flushes()")
	g.p("}")
	g.p("")
	g.p("// stmtFor compiles a read. LIMIT and LIMIT/OFFSET are different")
	g.p("// statements with different placeholder counts, so they get different")
	g.p("// caches rather than a sentinel token muddying the key.")
	g.p("func stmtFor(toks []runtime.Tok, withOffset bool) *runtime.Stmt {")
	g.p("\tc, suffix := cache, limitSuffix")
	g.p("\tif withOffset {")
	g.p("\t\tc, suffix = offsetCache, limitOffsetSuffix")
	g.p("\t}")
	g.p("\tif st := c.Get(toks); st != nil {")
	g.p("\t\treturn st")
	g.p("\t}")
	g.p("\treturn c.Put(toks, runtime.SpliceTree(selectPrefix, toks, lowering, suffix))")
	g.p("}")
	g.p("")
	g.p("// existsStmtFor compiles the existence probe: SELECT 1, no ORDER BY,")
	g.p("// LIMIT 1 — the planner stops at the first matching tuple instead of")
	g.p("// sorting every match to return the \"first\" of an order nobody reads.")
	g.p("func existsStmtFor(toks []runtime.Tok) *runtime.Stmt {")
	g.p("\tif st := existsCache.Get(toks); st != nil {")
	g.p("\t\treturn st")
	g.p("\t}")
	g.p("\treturn existsCache.Put(toks, runtime.SpliceTree(existsPrefix, toks, lowering, existsSuffix))")
	g.p("}")
	g.p("")
	g.p("func countStmtFor(toks []runtime.Tok) *runtime.Stmt {")
	g.p("\tif st := countCache.Get(toks); st != nil {")
	g.p("\t\treturn st")
	g.p("\t}")
	g.p("\t// A count ignores ordering as well as LIMIT: ordering a scalar is")
	g.p("\t// wasted work, and the token stream is trimmed before it gets here.")
	g.p("\treturn countCache.Put(toks, runtime.SpliceTree(countPrefix, toks, lowering, \"\"))")
	g.p("}")
	g.p("")
	g.p("// Composition seams, for the generated CONTEXT package and it alone:")
	g.p("// cross-table statements (a filtered semi-join spans two packages) are")
	g.p("// assembled there from each side's tokens, fragments and bindings. Ids")
	g.p("// only — no SQL text and no value crosses here.")
	g.p("")
	g.p("// FragOf is the compiled fragment table, exported for composition.")
	g.p("func FragOf(op, col uint32) runtime.Frag { return fragOf(op, col) }")
	g.p("")
	g.p("// Lowering is this package's back-end text, exported for composition.")
	g.p("func Lowering() runtime.Lowering { return lowering }")
	g.p("")
	g.p("// StmtPieces are the statement's constant parts, exported for composition.")
	g.p("func StmtPieces() (selectPfx, countPfx, limitSfx string) {")
	g.p("\treturn selectPrefix, countPrefix, limitSuffix")
	g.p("}")
	g.p("")
	g.p("// PredToks appends this query's predicate stream to dst: top-level")
	g.p("// conjuncts reduced to one entry, order excluded.")
	g.p("func (q Query) PredToks(dst []runtime.Tok) []runtime.Tok {")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\treturn append(dst, q.preds(&buf)...)")
	g.p("}")
	g.p("")
	g.p("// OrderToks appends this query's ordering — explicit, or the default")
	g.p("// unless Unordered.")
	g.p("func (q Query) OrderToks(dst []runtime.Tok) []runtime.Tok {")
	g.p("\tif q.no == 0 {")
	g.p("\t\tif q.noOrder {")
	g.p("\t\t\treturn dst")
	g.p("\t\t}")
	g.p("\t\treturn append(dst, defaultOrder[:]...)")
	g.p("\t}")
	g.p("\treturn append(dst, q.otoks[:q.no]...)")
	g.p("}")
	g.p("")
	g.p("// BindPreds binds this query's predicate values into b, appending to v.")
	g.p("func (q Query) BindPreds(b *Binder, v []any) []any {")
	g.p("\treturn append(v, q.bindPreds(b)...)")
	g.p("}")
	g.p("")
	g.p("// BindPaging appends the LIMIT (and OFFSET when set) arguments.")
	g.p("func (q Query) BindPaging(b *Binder, v []any) []any {")
	g.p("\tb.limit = q.limit")
	g.p("\tv = append(v, &b.limit)")
	g.p("\tif q.offset > 0 {")
	g.p("\t\tb.offset = q.offset")
	g.p("\t\tv = append(v, &b.offset)")
	g.p("\t}")
	g.p("\treturn v")
	g.p("}")
	g.p("")
	g.p("// Shape is a fingerprint of this query's structure — equal shapes share a")
	g.p("// compiled statement. Values do not contribute, which is the point.")
	g.p("func (q Query) Shape() uint64 {")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\treturn runtime.HashToks(q.stream(&buf))")
	g.p("}")
	g.p("")
	g.p("// SQL returns the compiled text for this query's structure.")
	g.p("func (q Query) SQL() string {")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\treturn stmtFor(q.stream(&buf), q.offset > 0).SQL")
	g.p("}")
	g.p("")
}

func (g *gen) scanner() {
	g.p("// Scan decodes one row from raw wire bytes into r, copying text into sl.")
	g.p("//")
	g.p("// Exported for the context package, which assembles batched results and")
	g.p("// therefore has to decode rows it did not issue the query for.")
	g.p("func Scan(rv [][]byte, r *Row, sl *runtime.Slab) error { return scan(rv, r, sl) }")
	g.p("")
	g.p("// scan decodes one row straight from the wire. No reflect, no `any`, no")
	g.p("// driver.Value: the generator knows every column's type already.")
	g.p("//")
	g.p("// It returns an error only for a value the Go type cannot carry — a")
	g.p("// numeric past 18 significant digits, or a NaN. Those must not become a")
	g.p("// plausible zero, and a row scanner is the last place that can tell.")
	g.p("func scan(rv [][]byte, r *Row, sl *runtime.Slab) error {")
	if g.hasFallibleDecode() {
		g.p("\tvar decErr error")
	}
	i := 0
	for _, c := range g.t.Columns {
		// Must match allReadable exactly: the scanner reads result columns
		// positionally, so one extra or one missing here shifts every value
		// after it into the wrong field.
		if !readable(c) {
			continue
		}
		g.p("\t%s", decodeExprIn(c, i, g.dec))
		if fallibleIn(c, g.dec) {
			// Return on the FIRST failure rather than letting the next
			// column's assignment overwrite decErr. The row is partly decoded
			// at that point and the caller discards it, which is the right
			// trade — carrying on would report the last error instead of the
			// one that mattered, and a test caught exactly that.
			g.p("\tif decErr != nil {")
			g.p("\t\treturn decErr")
			g.p("\t}")
		}
		i++
	}
	if g.hasFallibleDecode() {
		g.p("\treturn decErr")
	} else {
		g.p("\treturn nil")
	}
	g.p("}")
	g.p("")
}

func (g *gen) terminals() {
	g.p("// All runs the query and decodes every row.")
	g.p("func (q Query) All(ctx context.Context, ex runtime.Executor, dst []Row) ([]Row, error) {")
	g.p("\tvar sl runtime.Slab")
	g.p("\treturn q.AllInto(ctx, ex, dst, &sl)")
	g.p("}")
	g.p("")
	g.p("// AllInto lets the caller own the string arena.")
	g.p("func (q Query) AllInto(ctx context.Context, ex runtime.Executor, dst []Row, sl *runtime.Slab) ([]Row, error) {")
	g.p("\tif err := q.Err(); err != nil {")
	g.p("\t\treturn dst, err")
	g.p("\t}")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\tst := stmtFor(q.stream(&buf), q.offset > 0)")
	g.p("\tif st.Err != nil {")
	g.p("\t\t// A malformed token stream is a code-generation bug. Executing it")
	g.p("\t\t// would run a query whose filter is not the one that was asked for.")
	g.p("\t\treturn dst, st.Err")
	g.p("\t}")
	g.p("\tsl.Reserve(st.SlabHint())")
	g.p("\tb := binders.Get()")
	g.p("\tdefer putBinder(b)")
	g.p("")
	g.p("\trows, err := ex.Query(ctx, st.SQL, q.bind(b))")
	g.p("\tif err != nil {")
	g.p("\t\treturn dst, err")
	g.p("\t}")
	g.p("\tdefer rows.Close()")
	g.p("\tfor rows.Next() {")
	g.p("\t\tdst = append(dst, Row{})")
	g.p("\t\tif err := scan(rows.RawValues(), &dst[len(dst)-1], sl); err != nil {")
	g.p("\t\t\treturn dst, err")
	g.p("\t\t}")
	g.p("\t}")
	g.p("\tst.ObserveSlab(sl.Size())")
	g.p("\treturn dst, rows.Err()")
	g.p("}")
	g.p("")
	g.p("// One returns the first row, if any.")
	g.p("func (q Query) One(ctx context.Context, ex runtime.Executor) (Row, bool, error) {")
	g.p("\tvar sl runtime.Slab")
	g.p("\tvar buf [1]Row")
	g.p("\tout, err := q.Limit(1).AllInto(ctx, ex, buf[:0], &sl)")
	g.p("\tif err != nil || len(out) == 0 {")
	g.p("\t\treturn Row{}, false, err")
	g.p("\t}")
	g.p("\treturn out[0], true, nil")
	g.p("}")
	g.p("")
	g.p("// Count ignores Limit: counting a truncated set is a bug, not a feature.")
	g.p("func (q Query) Count(ctx context.Context, ex runtime.Executor) (int64, error) {")
	g.p("\tif err := q.Err(); err != nil {")
	g.p("\t\treturn 0, err")
	g.p("\t}")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\tst := countStmtFor(q.preds(&buf))")
	g.p("\tif st.Err != nil {")
	g.p("\t\t// A malformed token stream is a code-generation bug. Executing it")
	g.p("\t\t// would run a query whose filter is not the one that was asked for.")
	g.p("\t\treturn 0, st.Err")
	g.p("\t}")
	g.p("\tb := binders.Get()")
	g.p("\tdefer putBinder(b)")
	g.p("\t// bindPreds, not bind: a count has no LIMIT and no OFFSET. The old")
	g.p("\t// form bound everything and sliced the last argument off, which was")
	g.p("\t// the limit — unless Offset was set, in which case it silently kept")
	g.p("\t// the limit and dropped the offset, and the statement mismatched.")
	g.p("\trows, err := ex.Query(ctx, st.SQL, q.bindPreds(b))")
	g.p("\tif err != nil {")
	g.p("\t\treturn 0, err")
	g.p("\t}")
	g.p("\tdefer rows.Close()")
	g.p("\tvar n int64")
	g.p("\tif rows.Next() {")
	g.p("\t\tn = %s(rows.RawValues()[0])", g.dec.q("Int8"))
	g.p("\t}")
	g.p("\treturn n, rows.Err()")
	g.p("}")
	g.p("")
	g.p("// Exists asks the one-bit question with a one-bit statement: SELECT 1,")
	g.p("// no ORDER BY, LIMIT 1. It was previously One() with the row thrown")
	g.p("// away, which projected every column AND carried the default ordering —")
	g.p("// measured on 50k rows, the planner top-N-sorted all 16,667 matches to")
	g.p("// return the \"first\" of an order nobody was going to read.")
	g.p("func (q Query) Exists(ctx context.Context, ex runtime.Executor) (bool, error) {")
	g.p("\tif err := q.Err(); err != nil {")
	g.p("\t\treturn false, err")
	g.p("\t}")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\tst := existsStmtFor(q.preds(&buf))")
	g.p("\tif st.Err != nil {")
	g.p("\t\treturn false, st.Err")
	g.p("\t}")
	g.p("\tb := binders.Get()")
	g.p("\tdefer putBinder(b)")
	g.p("\trows, err := ex.Query(ctx, st.SQL, q.bindPreds(b))")
	g.p("\tif err != nil {")
	g.p("\t\treturn false, err")
	g.p("\t}")
	g.p("\tdefer rows.Close()")
	g.p("\treturn rows.Next(), rows.Err()")
	g.p("}")
	g.p("")
	g.p("// Prepare resolves the structure and binds arguments without executing.")
	g.p("func (q Query) Prepare(b *Binder) (string, []any) {")
	g.p("\tvar buf [%d]runtime.Tok", maxToks+maxOrder+1)
	g.p("\treturn stmtFor(q.stream(&buf), q.offset > 0).SQL, q.bind(b)")
	g.p("}")
	g.p("")
}

