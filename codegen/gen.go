// orderTerm is one default ORDER BY term, resolved to the ids generated code
// uses.
type orderTerm struct {
	col      int
	dirConst string
	comment  string
}

// defaultOrder is the ordering a query with no Order() gets.
//
// It is never empty: a read without ORDER BY has no defined order, so paging
// one is a bug waiting for a plan change to expose it. The primary key is the
// cheapest total order available, and Options.DefaultOrder overrides it.
func (g *gen) defaultOrder() []orderTerm {
	if len(g.o.DefaultOrder) > 0 {
		var out []orderTerm
		for _, t := range g.o.DefaultOrder {
			i := g.colIndex(t.Column)
			if i < 0 {
				g.err = fmt.Errorf(
					"codegen: table %s: default order names column %s, which is not filterable",
					g.t.Name, t.Column)
				return []orderTerm{{col: 0, dirConst: "runtime.Asc", comment: "invalid"}}
			}
			out = append(out, orderTerm{col: i, dirConst: dirConst(t.Desc), comment: t.Column})
		}
		return out
	}
	var out []orderTerm
	for _, k := range g.t.PrimaryKey {
		if i := g.colIndex(k); i >= 0 {
			out = append(out, orderTerm{col: i, dirConst: "runtime.Asc", comment: k})
		}
	}
	if len(out) == 0 {
		out = append(out, orderTerm{col: 0, dirConst: "runtime.Asc", comment: g.cols[0].Name()})
	}
	return out
}

func dirConst(desc bool) string {
	if desc {
		return "runtime.Desc"
	}
	return "runtime.Asc"
}

func (g *gen) colIndex(name string) int {
	for i, c := range g.cols {
		if c.Name() == name {
			return i
		}
	}
	return -1
}

// fallibleColumn reports whether one column's decoder can fail.
func fallibleColumn(c *schema.Column) bool {
	return fallibleIn(c, decodersFor(DialectPostgres, ""))
}

// fallibleIn asks the DIALECT whether this column's decode can fail.
//
// Not a property of the type alone. MySQL packs a DATETIME component-wise
// behind a leading length, so it can be handed one that does not match and its
// decoder returns an error; PostgreSQL reads a fixed-width epoch offset and
// cannot. Emitting the wrong answer produces a scanner that either drops an
// error or assigns two values to one variable — both compile failures in
// somebody else's tree.
func fallibleIn(c *schema.Column, d decoders) bool {
	return d.fallible[goKind(c)]
}

// hasFallibleDecode reports whether any column can fail to decode. Only
// numeric can: everything else has a Go type that carries every wire value.
func (g *gen) hasFallibleDecode() bool {
	for _, c := range g.t.Columns {
		if fallibleIn(c, g.dec) {
			return true
		}
	}
	return false
}
