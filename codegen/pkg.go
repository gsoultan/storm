package codegen

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strings"

	"github.com/gsoultan/raorm/schema"
)

// PackageOptions configures a whole-context generation.
type PackageOptions struct {
	// Dir is the output root. One directory per table is created under it.
	Dir string

	// Import is the module path of raorm, e.g. "github.com/gsoultan/raorm".
	Import string

	// Only restricts generation to these table names. Empty means every table
	// in the schema.
	Only []string

	// DefaultOrder overrides the default ordering per table. A table absent
	// from the map orders by its primary key.
	DefaultOrder map[string][]OrderTerm

	// PackageImport is the import path of the generated tree, e.g.
	// "example.com/app/internal/store". Required when Package is set.
	//
	// It is given rather than derived from Dir: an import path cannot be
	// recovered from a filesystem path without knowing where the module root
	// is, and guessing produces a package that does not compile — which is
	// exactly what the first cut of this did.
	PackageImport string

	// TopStrategy selects the greatest-n-per-group lowering for every table.
	TopStrategy TopStrategy

	// Package is the parent package that holds the context file: the flush
	// order and the Unit constructor. Empty skips it, which is what a
	// single-table generation wants.
	//
	// It is the parent because ordering spans tables, and a table package that
	// imported a sibling would reintroduce the import cycle one-package-per-
	// table exists to avoid. Named plans land here for the same reason.
	Package string
}

// Package renders one Go package per table and returns path → contents, with
// paths relative to Dir. Nothing is written; the caller decides that, so a
// generation that fails partway cannot leave a half-written tree behind.
//
// One package per table, not one package holding every table. That is what
// docs/API.md describes — `user.Row`, `user.Query()`, `user.ID` — and it is
// what keeps generated code readable: inside its own package a table's type is
// just Row, so nothing needs a UserRow / OrgRow prefix. Relations and named
// plans live in the parent package, which imports the table packages; since a
// table package never imports a sibling, a has-many in both directions cannot
// produce an import cycle.
func Package(s *schema.Schema, o PackageOptions) (map[string][]byte, error) {
	if o.Import == "" {
		return nil, fmt.Errorf("codegen: PackageOptions.Import is required")
	}

	names := o.Only
	if len(names) == 0 {
		for _, t := range s.Tables {
			names = append(names, t.Name)
		}
	}
	sort.Strings(names) // determinism does not depend on model declaration order

	out := make(map[string][]byte, len(names))
	seen := make(map[string]string, len(names))
	for _, name := range names {
		t := s.Table(name)
		if t == nil {
			return nil, fmt.Errorf("codegen: no table %q in the model", name)
		}
		pkg, err := PackageName(t.GoName, t.Name)
		if err != nil {
			return nil, err
		}
		if prev, dup := seen[pkg]; dup {
			// Two tables landing in one directory would silently overwrite
			// each other; better to name the collision.
			return nil, fmt.Errorf(
				"codegen: tables %q and %q both generate package %q — rename one with t.Name(...)",
				prev, name, pkg)
		}
		seen[pkg] = name

		src, err := File(s, Options{
			Package:         pkg,
			Import:          o.Import,
			Table:           name,
			DefaultOrder:    o.DefaultOrder[name],
			BatchTopColumns: batchTopColumns(s, name, names),
			TopStrategy:     o.TopStrategy,
		})
		if err != nil {
			return nil, err
		}
		out[filepath.Join(pkg, pkg+".gen.go")] = src
	}

	if o.Package != "" {
		if o.PackageImport == "" {
			return nil, fmt.Errorf(
				"codegen: PackageOptions.Package is %q but PackageImport is empty — "+
					"the context file imports the table packages and an import path "+
					"cannot be derived from a directory", o.Package)
		}
		src, err := contextFile(s, o, names)
		if err != nil {
			return nil, err
		}
		out[o.Package+".gen.go"] = src
	}
	return out, nil
}

// contextFile emits the bounded context's own package: the foreign-key flush
// order, a Unit built over it, and one plan type per relation.
func contextFile(s *schema.Schema, o PackageOptions, names []string) ([]byte, error) {
	rank, err := FlushOrder(s)
	if err != nil {
		return nil, err
	}
	plans, err := relPlansFor(s, names)
	if err != nil {
		return nil, err
	}

	// Emit the body first, then the imports it turned out to need. Emitting a
	// fixed import list instead means importing a table package with no
	// relations, and Go rejects an unused import — which is what the first cut
	// of this did on a nine-table fixture.
	named, err := namedPlansFor(s, names)
	if err != nil {
		return nil, err
	}

	var body gen
	body.emitRelPlans(plans)
	body.emitNamedPlans(named)

	var g gen
	g.p("// Code generated by raorm. DO NOT EDIT.")
	g.p("// source: bounded context %s", o.Package)
	g.p("")
	g.p("package %s", o.Package)
	g.p("")
	g.p("import (")
	if len(plans) > 0 || len(named) > 0 {
		g.p("\t%q", "context")
		if anyToOne(plans) || anyNamedToOne(named) {
			g.p("\t%q", "fmt")
		}
		g.p("")
	}
	g.p("\t%q", o.Import+"/runtime")
	for _, pkg := range planPackages(plans, named) {
		g.p("\t%q", o.PackageImport+"/"+pkg)
	}
	g.p(")")
	g.p("")
	g.p("// FlushOrder ranks tables so that every table's foreign-key targets rank")
	g.p("// strictly lower. It is computed at generate time from the model, so no")
	g.p("// runtime code inspects a schema and no constraint has to be deferred for")
	g.p("// a graph write to succeed.")
	g.p("var FlushOrder = map[string]int{")
	ordered := make([]string, 0, len(rank))
	for _, n := range names {
		if _, ok := rank[n]; ok {
			ordered = append(ordered, n)
		}
	}
	sort.Slice(ordered, func(i, j int) bool { return rank[ordered[i]] < rank[ordered[j]] })
	for _, n := range ordered {
		g.p("\t%q: %d,", n, rank[n])
	}
	g.p("}")
	g.p("")
	g.p("// NewUnit stages writes across this context and flushes them in foreign-key")
	g.p("// order as one round trip.")
	g.p("func NewUnit() *runtime.Unit { return runtime.NewUnit(FlushOrder) }")
	g.p("")
	if len(plans) > 0 || len(named) > 0 {
		g.p("// defaultChildLimit caps a relation load. Any constant is arbitrary — too")
		g.p("// low truncates a legitimate load, too high is the unbounded read the dba")
		g.p("// profile vetoes — so what is settled here is only the BEHAVIOUR on")
		g.p("// reaching it: an error, never a partial result. Override per plan with")
		g.p("// ChildLimit.")
		g.p("const defaultChildLimit = 1 << 20")
		g.p("")
	}
	g.buf.Write(body.buf.Bytes())

	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("codegen: context file does not parse: %w", err)
	}
	return src, nil
}

// planPackages is every table package the plan layer names, sorted.
func planPackages(plans []relPlan, named []namedPlan) []string {
	seen := map[string]bool{}
	var out []string
	add := func(pkgs ...string) {
		for _, pkg := range pkgs {
			if pkg != "" && !seen[pkg] {
				seen[pkg] = true
				out = append(out, pkg)
			}
		}
	}
	for _, p := range plans {
		add(p.ParentPkg, p.ChildPkg)
	}
	for _, np := range named {
		add(np.ParentPkg)
		for _, m := range np.members {
			add(m.ChildPkg)
		}
	}
	sort.Strings(out)
	return out
}

func anyNamedToOne(named []namedPlan) bool {
	for _, np := range named {
		for _, m := range np.members {
			if !m.rel.ToMany {
				return true
			}
		}
	}
	return false
}

func anyToOne(plans []relPlan) bool {
	for _, p := range plans {
		if !p.rel.ToMany {
			return true
		}
	}
	return false
}

// PackageName is the Go package a table generates into: the model type in
// lower case, so table "users" (from type User) becomes package "user".
//
// It uses the Go name rather than de-pluralising the table name, because
// pluralisation is not invertible — "users" → "user" is easy, "addresses" →
// "addres" is wrong, and English has no rule to appeal to. A table from
// introspection has no Go name, so it falls back to the table name and says so
// if that is not a usable identifier.
func PackageName(goName, table string) (string, error) {
	src := goName
	if src == "" {
		src = table
	}
	pkg := strings.Map(func(r rune) rune {
		switch {
		case r >= 'A' && r <= 'Z':
			return r + ('a' - 'A')
		case r >= 'a' && r <= 'z', r >= '0' && r <= '9':
			return r
		default:
			return -1 // _ and - are legal in a path but not idiomatic in a package name
		}
	}, src)
	if pkg == "" || (pkg[0] >= '0' && pkg[0] <= '9') {
		return "", fmt.Errorf(
			"codegen: table %q has no usable package name (from %q) — set one with t.Name(...)",
			table, src)
	}
	if isGoKeyword(pkg) {
		return "", fmt.Errorf(
			"codegen: table %q generates package %q, which is a Go keyword — rename the model or the table",
			table, pkg)
	}
	return pkg, nil
}

func isGoKeyword(s string) bool {
	switch s {
	case "break", "case", "chan", "const", "continue", "default", "defer", "else",
		"fallthrough", "for", "func", "go", "goto", "if", "import", "interface",
		"map", "package", "range", "return", "select", "struct", "switch", "type", "var":
		return true
	}
	return false
}

// batchTopColumns is every column of table that a has-many relation loads it
// by — the partition columns of a per-parent limited fetch.
//
// Computed here rather than in File because a table cannot see the relations
// pointing AT it: the relation is declared on the parent, and only a
// whole-context generation has both ends.
func batchTopColumns(s *schema.Schema, table string, in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, name := range in {
		t := s.Table(name)
		if t == nil {
			continue
		}
		for _, rel := range t.Relations {
			if !rel.ToMany || rel.Target != table {
				continue
			}
			if !seen[rel.Column] {
				seen[rel.Column] = true
				out = append(out, rel.Column)
			}
		}
	}
	sort.Strings(out)
	return out
}
