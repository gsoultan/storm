// FileEmbedded renders the package of a table embedded in its parent
// (storm.Embed): parent-scoped, since its rows have no collection — Of and
// Load read a parent's array, Add, Replace and Remove write it.
func FileEmbedded(s *schema.Schema, t *schema.Table, pkg, imp string) ([]byte, error) {
	r := mongo.EmbedOf(t)
	parent := s.Table(r.Target)
	if parent == nil || len(parent.PrimaryKey) != 1 || len(t.PrimaryKey) != 1 {
		return nil, fmt.Errorf("codegenmongo: %s: an embedded table and its parent each need a single-column key", t.Name)
	}
	g, err := newGen(nil, t, pkg, imp)
	if err != nil {
		return nil, err
	}
	if g.kind[g.keys[0]].slice {
		return nil, fmt.Errorf("codegenmongo: %s: an embedded table's key must be comparable — a bytea key is not", t.Name)
	}
	fi := g.index(r.Column)
	pk, ok := kindOf(parent.Column(parent.PrimaryKey[0]))
	if fi < 0 || !ok || g.kind[fi].goType != pk.goType || g.kind[fi].nullable(g.cols[fi]) {
		return nil, fmt.Errorf("codegenmongo: %s.%s must be a NOT NULL copy of %s's key", t.Name, r.Column, parent.Name)
	}
	g.embedded(parent, fi)
	src, err := format.Source(g.b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("codegenmongo: %s: generated source does not parse (a generator bug): %w\n%s",
			t.Name, err, g.b.Bytes())
	}
	return src, nil
}

// embedded emits the package. fi is the reference to the parent: a Row
// field, filled from the parent's _id, and never stored in the element.
func (g *gen) embedded(parent *schema.Table, fi int) {
	arr, ki := g.t.Name, g.keys[0]
	key, fk := g.field(ki), g.field(fi)
	keyType, fkType := g.kind[ki].goType, g.kind[fi].goType
	// The element's fields and their holes: 1 is the parent's key, 2 the
	// element's, the rest in column order.
	hole := map[int]int{fi: 1, ki: 2}
	var order []int
	next := 3
	for i := range g.cols {
		if i != fi && i != ki {
			hole[i] = next
			next++
			order = append(order, i)
		}
	}
	var lit, plain string
	for _, i := range append([]int{ki}, order...) {
		if lit != "" {
			lit, plain = lit+",", plain+","
		}
		v := `{"$literal":` + mongo.Arg(hole[i]) + `}`
		if k, _ := mongo.ClassifyDefault(g.cols[i]); k == mongo.DefaultServerTime {
			v = `{"$ifNull":[` + v + `,"$$NOW"]}`
		}
		lit += mongo.Str(g.stored(i)) + ":" + v
		plain += mongo.Str(g.stored(i)) + ":" + mongo.Arg(hole[i])
	}
	p, a := mongo.Str(parent.Name), mongo.Str(arr)
	id := mongo.Str(arr + "._id")
	add := `{"findAndModify":` + p + `,"query":{"_id":` + mongo.Arg(1) + `,` + id + `:{"$ne":` + mongo.Arg(2) +
		`}},"update":[{"$set":{` + a + `:{"$concatArrays":[{"$ifNull":["$` + arr + `",[]]},[{` + lit +
		`}]]}}}],"new":true,"fields":{"_id":1,` + a + `:{"$slice":-1}}}`
	replace := `{"update":` + p + `,"updates":[{"q":{"_id":` + mongo.Arg(1) + `,` + id + `:` + mongo.Arg(2) +
		`},"u":{"$set":{` + mongo.Str(arr+".$") + `:{` + plain + `}}}}]}`
	remove := `{"update":` + p + `,"updates":[{"q":{"_id":` + mongo.Arg(1) + `,` + id + `:` + mongo.Arg(2) +
		`},"u":{"$pull":{` + a + `:{"_id":` + mongo.Arg(2) + `}}}}]}`
	of := `{"find":` + p + `,"limit":1,"projection":{"_id":1,` + a + `:1},"filter":{"_id":` + mongo.Arg(1) + `}}`
	load := `{"find":` + p + `,"projection":{"_id":1,` + a + `:1},"filter":{"_id":{"$in":` + mongo.Arg(1) + `}}}`
	exists := `{"find":` + p + `,"limit":1,"projection":{"_id":1},"filter":{"_id":` + mongo.Arg(1) + `}}`

	g.p("// Code generated by storm for MongoDB. DO NOT EDIT.")
	g.p("")
	g.p("// Package %s is %s, embedded in each %s document as the array %q", g.pkg, g.t.Name, parent.Name, arr)
	g.p("// (storm.Embed). It has no collection, so it has no query of its own: a")
	g.p("// parent's rows are read with Of or Load and written with Add, Replace and")
	g.p("// Remove, each one command against the parent's document. They go when it")
	g.p("// goes, which is the ON DELETE CASCADE the model declared.")
	g.p("package %s", g.pkg)
	g.p("")
	g.p("import (")
	g.p("\t\"context\"")
	g.p("\t\"errors\"")
	g.p("\t\"time\"")
	g.p("")
	g.p("\t%q", g.imp+"/runtime")
	g.p("\t%q", g.imp+"/runtime/bsondec")
	g.p(")")
	g.p("")
	g.p("var _ = time.Time{}")
	g.p("")
	g.p("// Parent is the collection whose documents hold these rows, and Field the")
	g.p("// array they are held in.")
	g.p("const (")
	g.p("\tParent = %q", parent.Name)
	g.p("\tField  = %q", arr)
	g.p(")")
	g.p("")
	g.row()
	g.p("const (")
	for _, c := range []struct{ name, text string }{
		{"addCmd", add}, {"replaceCmd", replace}, {"removeCmd", remove},
		{"ofCmd", of}, {"loadCmd", load}, {"parentCmd", exists},
	} {
		g.p("\t%s = %s", c.name, strconv.Quote(c.text))
	}
	g.p(")")
	g.p("")
	g.p(`func orNil[T any](v []T) any {
	if v == nil {
		return nil
	}
	return v
}

func nullable[T any](n runtime.Null[T]) any {
	if !n.Valid {
		return nil
	}
	return n.V
}
`)
	g.p("// args are a row's holes: the parent's key, the element's, then the rest.")
	g.p("func (r *Row) args() []any {")
	g.p("\treturn []any{r.%s, r.%s,", fk, key)
	for _, i := range order {
		v := g.unwrap(i, "r."+g.field(i))
		if k, _ := mongo.ClassifyDefault(g.cols[i]); k == mongo.DefaultServerTime && !g.kind[i].nullable(g.cols[i]) {
			v = "zeroNil(r." + g.field(i) + ")"
		}
		g.p("\t\t%s,", v)
	}
	g.p("\t}")
	g.p("}")
	g.p("")
	g.p(`// zeroNil binds an unset time as null, which Add's $ifNull turns into the
// server's clock — a now() default, still the SERVER's.
func zeroNil(t time.Time) any {
	if t.IsZero() {
		return nil
	}
	return t
}
`)
	keyFill := `return errors.New("storm: ` + g.t.Name + `.Add: must set ` + key + `")`
	switch k, _ := mongo.ClassifyDefault(g.cols[ki]); k {
	case mongo.DefaultUUIDv4:
		keyFill = "r." + key + " = runtime.NewUUIDv4()"
	case mongo.DefaultUUIDv7:
		keyFill = "r." + key + " = runtime.NewUUIDv7()"
	}
	g.p(`// Add appends r to the array of the parent r.%[1]s names, and reads the
// element back into r, so the server's defaults land in it. A zero key is
// filled in when the key has a default. A parent that is not there is
// runtime.ErrForeignKeyViolation — the constraint SQL would enforce, here
// one command's answer — and a key the parent already holds is
// runtime.ErrUniqueViolation.
func Add(ctx context.Context, ex runtime.Executor, r *Row) error {
	if r.%[2]s == *new(%[3]s) {
		%[4]s
	}
	rows, err := ex.Query(ctx, addCmd, r.args())
	if err != nil {
		return err
	}
	defer rows.Close()
	if !rows.Next() {
		if err := rows.Err(); err != nil {
			return err
		}
		return whyNot(ctx, ex, r.%[1]s)
	}
	rv := rows.RawValues()
	var added Row
	n := 0
	if err := elements(rv[0], rv[1], func(e Row) error { added, n = e, n+1; return nil }); err != nil {
		return err
	}
	if n != 1 {
		return runtime.ErrShape
	}
	*r = added
	return rows.Err()
}

// whyNot tells a missing parent from a duplicate key, after an Add that
// matched nothing.
func whyNot(ctx context.Context, ex runtime.Executor, parent %[5]s) error {
	rows, err := ex.Query(ctx, parentCmd, []any{parent})
	if err != nil {
		return err
	}
	defer rows.Close()
	if rows.Next() {
		return errors.Join(runtime.ErrUniqueViolation, errors.New("storm: %[6]s: the parent already holds this key"))
	}
	if err := rows.Err(); err != nil {
		return err
	}
	return errors.Join(runtime.ErrForeignKeyViolation, errors.New("storm: %[6]s: no %[7]s document has this key"))
}

// Replace writes every column of r over the element with r's key, in the
// parent r.%[1]s names. No such element is runtime.ErrNoRow.
func Replace(ctx context.Context, ex runtime.Executor, r Row) error {
	n, err := ex.Exec(ctx, replaceCmd, r.args())
	if err != nil {
		return err
	}
	if n == 0 {
		return runtime.ErrNoRow
	}
	return nil
}

// Remove deletes the element with this key from the parent's array. No such
// element is runtime.ErrNoRow.
func Remove(ctx context.Context, ex runtime.Executor, parent %[5]s, key %[3]s) error {
	n, err := ex.Exec(ctx, removeCmd, []any{parent, key})
	if err != nil {
		return err
	}
	if n == 0 {
		return runtime.ErrNoRow
	}
	return nil
}

// Of reads one parent's rows, in array order. A parent that is not there
// has none.
func Of(ctx context.Context, ex runtime.Executor, parent %[5]s) ([]Row, error) {
	rows, err := ex.Query(ctx, ofCmd, []any{parent})
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Row
	for rows.Next() {
		rv := rows.RawValues()
		if err := elements(rv[0], rv[1], func(e Row) error { out = append(out, e); return nil }); err != nil {
			return nil, err
		}
	}
	return out, rows.Err()
}

// Load reads the rows of several parents in one command, by parent key.
func Load(ctx context.Context, ex runtime.Executor, parents ...%[5]s) (map[%[5]s][]Row, error) {
	out := make(map[%[5]s][]Row, len(parents))
	if len(parents) == 0 {
		return out, nil
	}
	rows, err := ex.Query(ctx, loadCmd, []any{parents})
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	for rows.Next() {
		rv := rows.RawValues()
		if err := elements(rv[0], rv[1], func(e Row) error {
			out[e.%[1]s] = append(out[e.%[1]s], e)
			return nil
		}); err != nil {
			return nil, err
		}
	}
	return out, rows.Err()
}
`, fk, key, keyType, keyFill, fkType, g.t.Name, parent.Name)
	g.p("// elements decodes a parent's array; parent is its _id, which every element's")
	g.p("// %s is.", fk)
	g.p("func elements(parent, arr []byte, fn func(Row) error) error {")
	g.p("\tif arr == nil {")
	g.p("\t\treturn nil")
	g.p("\t}")
	g.p("\tif arr[0] != bsondec.TArray {")
	g.p("\t\treturn runtime.ErrShape")
	g.p("\t}")
	g.p("\treturn bsondec.Elements(arr[1:], func(t byte, _ string, v []byte) error {")
	g.p("\t\tif t != bsondec.TDocument {")
	g.p("\t\t\treturn runtime.ErrShape")
	g.p("\t\t}")
	g.p("\t\trv := make([][]byte, nCols)")
	g.p("\t\trv[%d] = parent", fi)
	g.p("\t\terr := bsondec.Elements(v, func(t byte, name string, x []byte) error {")
	g.p("\t\t\tif t == bsondec.TNull {")
	g.p("\t\t\t\treturn nil")
	g.p("\t\t\t}")
	g.p("\t\t\tswitch name {")
	for _, i := range append([]int{ki}, order...) {
		g.p("\t\t\tcase %q:", g.stored(i))
		g.p("\t\t\t\trv[%d] = append([]byte{t}, x...)", i)
	}
	g.p("\t\t\t}")
	g.p("\t\t\treturn nil")
	g.p("\t\t})")
	g.p("\t\tif err != nil {")
	g.p("\t\t\treturn err")
	g.p("\t\t}")
	g.p("\t\tvar r Row")
	g.p("\t\tif err := scan(rv, &r); err != nil {")
	g.p("\t\t\treturn err")
	g.p("\t\t}")
	g.p("\t\treturn fn(r)")
	g.p("\t})")
	g.p("}")
	g.p("")
	g.scan()
}
