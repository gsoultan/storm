package codegenmongo

import (
	"bytes"
	"fmt"

	"github.com/gsoultan/storm/compile/mongo"
	"github.com/gsoultan/storm/schema"
)

// gen emits one table package.
type gen struct {
	b    bytes.Buffer
	t    *schema.Table
	pkg  string
	imp  string
	cols []*schema.Column
	kind []kind
	// keys are the primary key's columns, in key order.
	keys []int
	// version and soft are the version and soft-delete columns, or -1.
	version, soft int
	// guards are the counters with a guarded increment (IncWhen), in column
	// order; guard j takes expression bit nCols+j.
	guards []int
	// plan is the referential actions a delete performs, or nil.
	plan []cascadeNode
	// joins are the declared joins' stages after the call-site $match.
	joins []string
}

func newGen(s *schema.Schema, t *schema.Table, pkg, imp string) (*gen, error) {
	g := &gen{t: t, pkg: pkg, imp: imp, version: -1, soft: -1}
	var err error
	if g.plan, err = cascadePlan(s, t); err != nil {
		return nil, err
	}
	for _, j := range t.Joins {
		if s == nil {
			return nil, fmt.Errorf("codegenmongo: %s: join %s needs the whole model", t.Name, j.Name)
		}
		tail, err := mongo.Join(s, t, j)
		if err != nil {
			return nil, fmt.Errorf("codegenmongo: %s: join %s: %w", t.Name, j.Name, err)
		}
		g.joins = append(g.joins, tail)
	}
	for i, c := range t.Columns {
		k, ok := kindOf(c)
		if !ok {
			return nil, fmt.Errorf("codegenmongo: %s.%s: type %s has no MongoDB form", t.Name, c.Name, c.Type.SQL())
		}
		g.cols = append(g.cols, c)
		g.kind = append(g.kind, k)
		if c.Version {
			g.version = i
		}
		if c.Name == t.SoftDelete {
			g.soft = i
		}
		if c.IncWhen != "" {
			g.guards = append(g.guards, i)
		}
	}
	for _, k := range t.PrimaryKey {
		i := g.index(k)
		if i < 0 {
			return nil, fmt.Errorf("codegenmongo: %s: primary key %s is not a column", t.Name, k)
		}
		g.keys = append(g.keys, i)
	}
	if len(g.keys) == 0 {
		return nil, fmt.Errorf("codegenmongo: %s has no primary key", t.Name)
	}
	if len(g.cols)+len(g.guards) > 64 {
		return nil, fmt.Errorf("codegenmongo: %s has %d columns and %d guarded increments; a write's masks hold 64",
			t.Name, len(g.cols), len(g.guards))
	}
	if t.SoftDeletes() && g.soft < 0 {
		return nil, fmt.Errorf("codegenmongo: %s: soft-delete column %s is not a column", t.Name, t.SoftDelete)
	}
	if g.version >= 0 && !g.kind[g.version].counter {
		return nil, fmt.Errorf("codegenmongo: %s.%s: a version column must be an integer", t.Name, g.cols[g.version].Name)
	}
	for _, i := range g.guards {
		c := g.cols[i]
		w := g.index(c.IncWhen)
		if !g.kind[i].counter || !c.NotNull {
			return nil, fmt.Errorf("codegenmongo: %s: IncWhen on %s: the counter must be a NOT NULL integer", t.Name, c.Name)
		}
		if w < 0 || !g.kind[w].scalar() || g.kind[w].slice {
			return nil, fmt.Errorf("codegenmongo: %s: IncWhen on %s reads %s, which is not a column = can compare", t.Name, c.Name, c.IncWhen)
		}
	}
	return g, nil
}

func (g *gen) index(name string) int {
	for i, c := range g.cols {
		if c.Name == name {
			return i
		}
	}
	return -1
}

func (g *gen) isKey(i int) bool {
	for _, k := range g.keys {
		if k == i {
			return true
		}
	}
	return false
}

func (g *gen) p(format string, a ...any) {
	fmt.Fprintf(&g.b, format, a...)
	g.b.WriteByte('\n')
}

func (g *gen) field(i int) string  { return schema.GoName(g.cols[i].Name) }
func (g *gen) stored(i int) string { return mongo.Field(g.t, g.cols[i].Name) }

func (g *gen) fields() []string {
	out := make([]string, len(g.cols))
	for i := range g.cols {
		out[i] = g.stored(i)
	}
	return out
}

func (g *gen) emit() {
	g.header()
	g.row()
	g.handles()
	g.query()
	g.reads()
	g.projections()
	g.aggregates()
	g.declaredJoins()
	g.writes()
	g.scan()
}

func (g *gen) header() {
	g.p("// Code generated by storm for MongoDB. DO NOT EDIT.")
	g.p("")
	g.p("// Package %s is the %s collection, generated for MongoDB.", g.pkg, g.t.Name)
	g.p("//")
	g.p("// Every statement here is a command document compiled at generate time by")
	g.p("// compile/mongo; runtime/mgdrv runs it. See docs/DIALECTS.md for where this")
	g.p("// back end's answers differ from the SQL targets', and why.")
	g.p("package %s", g.pkg)
	g.p("")
	g.p("import (")
	g.p("\t\"context\"")
	g.p("\t\"errors\"")
	g.p("\t\"time\"")
	g.p("")
	g.p("\t%q", g.imp+"/runtime")
	g.p("\t%q", g.imp+"/runtime/bsondec")
	g.p("\t%q", g.imp+"/runtime/hooks")
	if g.plan != nil {
		g.p("\t%q", g.imp+"/runtime/mgcascade")
	}
	g.p("\t%q", g.imp+"/runtime/mgsplice")
	g.p(")")
	g.p("")
	g.p("var (")
	g.p("\t_ = time.Time{}")
	g.p("\t_ = errors.New")
	g.p("\t_ = bsondec.Str")
	g.p(")")
	g.p("")
	g.p("// Collection is where these documents live.")
	g.p("const Collection = %q", g.t.Name)
	g.p("")
}

func (g *gen) row() {
	g.p("// Row is one document: the model's columns, with *T rewritten to Null[T].")
	if len(g.keys) == 1 {
		g.p("// The primary key is stored as _id.")
	} else {
		g.p("// The primary key is stored as _id, a subdocument of its columns in key order.")
	}
	g.p("type Row struct {")
	for i, c := range g.cols {
		g.p("\t%s %s", g.field(i), g.kind[i].fieldType(c))
	}
	g.p("}")
	g.p("")
	g.p("const nCols = %d", len(g.cols))
	g.p("")
	g.p("// fields are the stored names, in column order: the projection every read")
	g.p("// asks for, so a row's values arrive in the order scan reads them.")
	g.p("var fields = [nCols]string{")
	for i := range g.cols {
		g.p("\t%q,", g.stored(i))
	}
	g.p("}")
	g.p("")
}

func (g *gen) handles() {
	g.p("// Operator ids, in compile/mongo's order.")
	g.p("const (")
	for i, op := range mongo.Ops() {
		g.p("\top%s uint8 = %d", op, i+1)
	}
	g.p(")")
	g.p("")
	g.p("// Pred is one comparison on one column.")
	g.p("type Pred struct {")
	g.p("\tcol, op uint8")
	g.p("\tv       any")
	g.p("\terr     error")
	g.p("}")
	g.p("")
	g.p("// Sort is one ordering term.")
	g.p("type Sort runtime.Tok")
	g.p("")

	seen := map[string]bool{}
	for i := range g.cols {
		k := g.kind[i]
		if seen[k.handle] {
			continue
		}
		seen[k.handle] = true
		switch {
		case k.array:
			g.arrayHandle(k)
		case k.json:
			g.jsonHandle(k)
		default:
			g.handle(k)
		}
	}
	g.p("// The columns.")
	g.p("var (")
	for i := range g.cols {
		g.p("\t%s = %s{c: %d}", g.field(i), g.kind[i].handle, i)
	}
	g.p(")")
	g.p("")
}

func (g *gen) nullOps(h string) {
	g.p("// IsNull matches a value that is null or absent.")
	g.p("func (h %s) IsNull() Pred { return Pred{col: h.c, op: opIsNull} }", h)
	g.p("")
	g.p("func (h %s) IsNotNull() Pred { return Pred{col: h.c, op: opIsNotNull} }", h)
	g.p("")
}

func (g *gen) handle(k kind) {
	h := k.handle
	t := k.goType
	g.p("// %s is a %s column.", h, t)
	g.p("type %s struct{ c uint8 }", h)
	g.p("")
	g.p("// Asc orders ascending. MongoDB places null and missing values FIRST in")
	g.p("// ascending order, where PostgreSQL places them last.")
	g.p("func (h %s) Asc() Sort { return Sort(runtime.MakeOrder(runtime.Asc, uint32(h.c))) }", h)
	g.p("")
	g.p("// Desc orders descending, null and missing values last.")
	g.p("func (h %s) Desc() Sort { return Sort(runtime.MakeOrder(runtime.Desc, uint32(h.c))) }", h)
	g.p("")
	g.p("func (h %s) Eq(v %s) Pred { return Pred{col: h.c, op: opEq, v: v} }", h, t)
	g.p("")
	g.p("// NotEq does not match a null or missing value, as SQL's <> does not.")
	g.p("func (h %s) NotEq(v %s) Pred { return Pred{col: h.c, op: opNotEq, v: v} }", h, t)
	g.p("")
	g.nullOps(h)
	if k.ordered {
		for _, op := range []string{"Gt", "Gte", "Lt", "Lte"} {
			g.p("func (h %s) %s(v %s) Pred { return Pred{col: h.c, op: op%s, v: v} }", h, op, t, op)
		}
		g.p("")
	}
	if k.listable {
		g.p("// In binds the whole list as one value, so the command does not depend on")
		g.p("// how many values were passed.")
		g.p("func (h %s) In(v ...%s) Pred { return Pred{col: h.c, op: opIn, v: v} }", h, t)
		g.p("")
		g.p("// NotIn does not match a null or missing value, as SQL's NOT IN does not.")
		g.p("func (h %s) NotIn(v ...%s) Pred { return Pred{col: h.c, op: opNotIn, v: v} }", h, t)
		g.p("")
	}
	if k.text {
		g.p("// HasPrefix matches a literal prefix — v is text, not a pattern. Anchored,")
		g.p("// so an index on the field can answer it.")
		g.p("func (h %s) HasPrefix(v string) Pred { return Pred{col: h.c, op: opHasPrefix, v: mgsplice.Prefix(v)} }", h)
		g.p("")
		g.p("// HasSuffix matches a literal suffix.")
		g.p("func (h %s) HasSuffix(v string) Pred { return Pred{col: h.c, op: opHasSuffix, v: mgsplice.Suffix(v)} }", h)
		g.p("")
		g.p("// Contains matches a literal substring.")
		g.p("func (h %s) Contains(v string) Pred { return Pred{col: h.c, op: opContains, v: mgsplice.Contains(v)} }", h)
		g.p("")
		g.p("// Like matches a SQL LIKE pattern: %% is any run, _ one character.")
		g.p("func (h %s) Like(v string) Pred { return Pred{col: h.c, op: opLike, v: mgsplice.Like(v)} }", h)
		g.p("")
		g.p("// ILike is Like, ignoring case.")
		g.p("func (h %s) ILike(v string) Pred { return Pred{col: h.c, op: opILike, v: mgsplice.Like(v)} }", h)
		g.p("")
	}
}

// arrayHandle is an array column's operators: the three set comparisons
// PostgreSQL has, with its answers. There is no ordering and no equality —
// MongoDB orders an array by its least element and matches equality
// element-wise, and neither is what SQL means.
func (g *gen) arrayHandle(k kind) {
	h, e := k.handle, k.elem
	g.p("// %s is an array column, stored as a BSON array.", h)
	g.p("type %s struct{ c uint8 }", h)
	g.p("")
	g.nullOps(h)
	g.p("// Contains is `@>`: every element of v is in the column. An empty v is")
	g.p("// true for every row that has an array, as it is in SQL.")
	g.p("func (h %s) Contains(v ...%s) Pred {", h, e)
	g.p("\tif len(v) == 0 {")
	g.p("\t\treturn Pred{col: h.c, op: opIsNotNull}")
	g.p("\t}")
	g.p("\treturn Pred{col: h.c, op: opArrayContains, v: v}")
	g.p("}")
	g.p("")
	g.p("// ContainedBy is `<@`: every element of the column is in v.")
	g.p("func (h %s) ContainedBy(v ...%s) Pred {", h, e)
	g.p("\tif v == nil {")
	g.p("\t\tv = []%s{}", e)
	g.p("\t}")
	g.p("\treturn Pred{col: h.c, op: opArrayContainedBy, v: v}")
	g.p("}")
	g.p("")
	g.p("// Overlaps is `&&`: the column and v share an element.")
	g.p("func (h %s) Overlaps(v ...%s) Pred {", h, e)
	g.p("\tif v == nil {")
	g.p("\t\tv = []%s{}", e)
	g.p("\t}")
	g.p("\treturn Pred{col: h.c, op: opArrayOverlaps, v: v}")
	g.p("}")
	g.p("")
}

// jsonHandle is a json column's operators. Contains, HasAnyKey and HasAllKeys
// bind a filter mgsplice builds from the caller's document; ContainedBy and
// TextLikeAny are not generated — MongoDB has no filter that says either.
func (g *gen) jsonHandle(k kind) {
	h := k.handle
	g.p("// %s is a json column, stored as the BSON value its text denotes.", h)
	g.p("type %s struct{ c uint8 }", h)
	g.p("")
	g.nullOps(h)
	g.p("// IsEmpty matches null, absent, {} and [].")
	g.p("func (h %s) IsEmpty() Pred { return Pred{col: h.c, op: opJSONIsEmpty} }", h)
	g.p("")
	g.p("// Contains is `@>`: every path v states holds in the column, with")
	g.p("// PostgreSQL's answer for an array that merely holds a scalar. A key that")
	g.p("// cannot be a field path — empty, $-prefixed, dotted — is an error the")
	g.p("// query returns, never a filter that matches something else.")
	g.p("func (h %s) Contains(v runtime.JSON) Pred {", h)
	g.p("\tf, err := mgsplice.JSONContains(fields[h.c], v)")
	g.p("\treturn Pred{col: h.c, op: opJSONContains, v: f, err: err}")
	g.p("}")
	g.p("")
	g.p("// HasAnyKey is `?|`: the column has at least one of the keys.")
	g.p("func (h %s) HasAnyKey(v ...string) Pred {", h)
	g.p("\tf, err := mgsplice.HasKeys(fields[h.c], v, false)")
	g.p("\treturn Pred{col: h.c, op: opHasAnyKey, v: f, err: err}")
	g.p("}")
	g.p("")
	g.p("// HasAllKeys is `?&`: the column has every one of the keys.")
	g.p("func (h %s) HasAllKeys(v ...string) Pred {", h)
	g.p("\tf, err := mgsplice.HasKeys(fields[h.c], v, true)")
	g.p("\treturn Pred{col: h.c, op: opHasAllKeys, v: f, err: err}")
	g.p("}")
	g.p("")
}
